def get_niche_prompt_context(niche_key: str) -> dict | None:
    """
    Returns a formatted prompt context dictionary for a given niche key.
    Includes all design tokens and content hints for the AI website generator.
    Returns None if niche not found.
    """
    niche = NICHES.get(niche_key)
    if not niche:
        return None

    return {
        "niche_key": niche_key,
        "niche_name": niche["name"],
        "design": {
            "colors": niche["colors"],
            "typography": niche["typography"],
            "layout": niche["layout"],
        },
        "content": {
            "image_keywords": niche["image_keywords"],
            "sections": niche["sections"],
        },
        "prompt_hint": (
            f"This is a {niche['name']} website. "
            f"Use a {niche['typography']['style'].lower()} typographic style. "
            f"The layout should feature: {niche['layout']}. "
            f"Recommended sections: {', '.join(niche['sections'])}."
        ),
    }


def detect_niche(prompt: str) -> str | None:
    """
    Auto-detects the most likely niche from a user's prompt text.
    Uses word-boundary keyword matching against the KEYWORD_MAP.
    Returns the niche key with the highest match count, or None if no match.
    """
    import re

    prompt_lower = prompt.lower()
    best_match = None
    best_score = 0

    for niche_key, keywords in KEYWORD_MAP.items():
        score = 0
        for keyword in keywords:
            kw = keyword.lower()
            # Use word boundary matching to avoid partial matches (e.g. "ai" in "dubai")
            pattern = r"\b" + re.escape(kw) + r"\b"
            if re.search(pattern, prompt_lower):
                # Longer keyword matches get higher weight
                score += len(kw.split()) * 2 + len(kw)
        if score > best_score:
            best_score = score
            best_match = niche_key

    return best_match if best_score > 0 else None


